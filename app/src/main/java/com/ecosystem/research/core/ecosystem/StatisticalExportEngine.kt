        val mdCellContent = """# Meta-Analysis: ${escapeJson(matrix.title)}\nGenerated by Research App v2.2\n\nThis notebook loads the extracted evidence records, calculates Risk Ratios and 95% Confidence Intervals, performs fixed and random effects meta-analysis pooling, and plots a publication-ready forest plot."""
        val codeCellData = """import numpy as np\nimport pandas as pd\nimport matplotlib.pyplot as plt\n\n# Assembled study records from Research App Evidence Matrix\ndf = pd.DataFrame({\n    'study': [$studiesPy],\n    'events_exp': [$eePy],\n    'total_exp': [$nePy],\n    'events_ctrl': [$ecPy],\n    'total_ctrl': [$ncPy]\n})\n\n# Compute Risk Ratios (RR) and Standard Errors\ndf['p_exp'] = df['events_exp'] / df['total_exp']\ndf['p_ctrl'] = df['events_ctrl'] / df['total_ctrl']\ndf['rr'] = df['p_exp'] / df['p_ctrl']\ndf['log_rr'] = np.log(df['rr'])\ndf['se_log_rr'] = np.sqrt((1/df['events_exp']) - (1/df['total_exp']) + (1/df['events_ctrl']) - (1/df['total_ctrl']))\ndf['ci_lower'] = np.exp(df['log_rr'] - 1.96 * df['se_log_rr'])\ndf['ci_upper'] = np.exp(df['log_rr'] + 1.96 * df['se_log_rr'])\n\nprint(df[['study', 'rr', 'ci_lower', 'ci_upper']])"""
