    /**
     * Generates a plain runnable Python (.py) script.
     */
    fun generatePythonScript(
        matrix: EvidenceMatrix,
        sources: List<Source>,
        cells: List<MatrixCell>
    ): String {
        val records = parseStudyRecords(sources, cells)
        val isoDate = SimpleDateFormat("yyyy-MM-dd HH:mm:ss", Locale.US).format(Date())

        val studiesPy = records.joinToString(", ") { "\"${escapeR(it.studyLabel)}\"" }
        val eePy = records.joinToString(", ") { it.eventsExp.toString() }
        val nePy = records.joinToString(", ") { it.sampleSizeExp.toString() }
        val ecPy = records.joinToString(", ") { it.eventsCtrl.toString() }
        val ncPy = records.joinToString(", ") { it.sampleSizeCtrl.toString() }

        return """
# ==============================================================================
# Meta-Analysis Python Script
# Generated by Research App v2.2 for Matrix: ${matrix.title}
# Date: $isoDate
# ==============================================================================

import numpy as np
import pandas as pd
import matplotlib.pyplot as plt

# 1. Dataset from Evidence Matrix
df = pd.DataFrame({
    'study': [$studiesPy],
    'events_exp': [$eePy],
    'total_exp': [$nePy],
    'events_ctrl': [$ecPy],
    'total_ctrl': [$ncPy]
})

# 2. Compute Effect Sizes (Risk Ratio) and 95% Confidence Intervals
df['p_exp'] = df['events_exp'] / df['total_exp']
df['p_ctrl'] = df['events_ctrl'] / df['total_ctrl']
df['rr'] = df['p_exp'] / df['p_ctrl']
df['log_rr'] = np.log(df['rr'])
df['se_log_rr'] = np.sqrt((1/df['events_exp']) - (1/df['total_exp']) + (1/df['events_ctrl']) - (1/df['total_ctrl']))
df['ci_lower'] = np.exp(df['log_rr'] - 1.96 * df['se_log_rr'])
df['ci_upper'] = np.exp(df['log_rr'] + 1.96 * df['se_log_rr'])

print("=== Evidence Summary Table ===")
print(df[['study', 'events_exp', 'total_exp', 'events_ctrl', 'total_ctrl', 'rr', 'ci_lower', 'ci_upper']])

# 3. Plot Publication Forest Plot
fig, ax = plt.subplots(figsize=(10, max(4, len(df) * 0.8)))
y_pos = np.arange(len(df))

ax.errorbar(
    df['rr'], y_pos,
    xerr=[df['rr'] - df['ci_lower'], df['ci_upper'] - df['rr']],
    fmt='s', color='navy', ecolor='darkblue', elinewidth=2, capsize=4, markersize=8
)

ax.axvline(1.0, color='red', linestyle='--', linewidth=1.5, label='No Effect (RR = 1.0)')
ax.set_yticks(y_pos)
ax.set_yticklabels(df['study'], fontsize=11)
ax.set_xlabel('Risk Ratio (95% CI)', fontsize=12)
ax.set_title('${escapeR(matrix.title)}', fontsize=14, fontweight='bold')
ax.grid(axis='x', linestyle=':', alpha=0.6)
ax.legend()
plt.tight_layout()

plt.savefig("python_forest_plot.png", dpi=300)
print("\nGenerated high-res forest plot: python_forest_plot.png")
""".trimIndent()
    }
}
